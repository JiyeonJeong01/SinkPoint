using UnityEngine;

/// <summary>
/// 몬스터 AI가 공통으로 사용하는 가장 작은 상태 목록입니다.
/// 존별 몬스터가 서로 다른 이동 방식을 쓰더라도 감지, 추적, 공격, 사망 흐름은 이 값으로 맞춥니다.
/// </summary>
public enum MonsterState
{
    // 대기 상태입니다. 아직 목적지나 추적 대상이 없을 때 사용합니다.
    Idle,

    // 지정된 waypoint route를 따라 이동하는 상태입니다.
    RouteMove,

    // 감지한 플레이어를 현재 이동 규칙으로 추적하는 상태입니다.
    Chase,

    // 플레이어가 공격 거리 안에 들어와 몸빵이나 패턴을 실행하는 상태입니다.
    Attack,

    // 표면을 잃었거나 중력 변화로 떨어지는 중인 상태입니다.
    Falling,

    // 체력이 0이 되어 더 이상 행동하지 않는 상태입니다.
    Dead
}
